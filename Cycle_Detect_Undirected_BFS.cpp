bool bfs(int i,vector<vector<ll>>&al,vector<bool>&vis){
    queue<pair<ll,ll>>q; 
    vis[i]=true;
    q.push({i,-1});
    while(!q.empty()){
        ll k=q.front().f; ll papa=q.front().s;
        for(int j=0;j<al[k].size();j++){
            
            if(vis[al[k][j]] && al[k][j]!=papa){return true;}
            if(!vis[al[k][j]]){q.push({al[k][j],q.front().f}); vis[al[k][j]]=true;}
        }
        q.pop();
    }
    return false;
}
int main(){
    cin.tie(nullptr); cout.tie(nullptr); ios::sync_with_stdio(false);
    ll n,m; cin>>n>>m;
    vector<vector<ll>>al(n+1);
    for(int i=0;i<m;i++){
        ll u,v; cin>>u>>v;
        al[u].push_back(v); al[v].push_back(u);
    }
    bool flag=false;
    vector<bool>vis(n+1,0); //for disconnected components. in case nodes of compo1 dont have cycle, we need to check nodes of other compos.
    for(int i=1;i<n+1;i++){
        if(!vis[i]){
            if(bfs(i,al,vis)){flag=true; break;}
        }
    }
    if(flag){cout<<"cycle found";}
}  











