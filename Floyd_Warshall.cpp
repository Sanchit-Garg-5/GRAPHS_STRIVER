int main(){
    cin.tie(nullptr); cout.tie(nullptr); ios::sync_with_stdio(false);
    ll n,m; cin>>n>>m;
    //create a distance matrix-adjacency matrix style
    vector<vector<ll>>me(n+1,vector<ll>(n+1,LLONG_MAX));
    //mark self distances from i->i as 0
    for(int i=1;i<n+1;i++){
        me[i][i]=0;
    }
    ////mark u->v with w (and if v->u exists,then mark v->u with w also)
    for(int i=0;i<m;i++){
        ll u,v,w; cin>>u>>v>>w;
        /* me[u][v]=w; me[v][u]=w; //if undirected
        */
        /* me[u][v]=w; //if directed
        */
    }
    //run for all intermediate k nodes,such that dist[i][j]=min(curr,dist[i][k]+dist[k][j]
    for(int k=1;k<n+1;k++){
        for(int i=1;i<n+1;i++){
            for(int j=1;j<n+1;j++){
                ll x=me[i][k],y=me[k][j];
                if(x!=LLONG_MAX && y!=LLONG_MAX){
                    me[i][j]=min(me[i][j],x+y);
                }
            }
        }
    }
    //below if for checking if negative cycles,then dist[i][i]<0 would exist
    bool flag=false;
    for(int i=1;i<n+1;i++){
        if(me[i][i]<0){flag=true; break;}
    }
    if(flag){cout<<-1;}
}

